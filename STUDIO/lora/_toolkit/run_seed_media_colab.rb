# The seed-media lane: render every photograph the three RAILS apps seed with.
#
#   ruby STUDIO/lora/_toolkit/run_seed_media_colab.rb
#
# Writes STUDIO/lora/seed_media.ipynb. Commit it, open it from the GitHub URL
# this prints, set HF_TOKEN in the sidebar, and run.
#
# A separate generator from run_train_colab.rb rather than a fourth flag on it,
# because that script is subject-scoped — it aborts without SUBJECT and writes
# into SUBJECT_DIR. This set spans three apps and two thirds of it has no subject
# at all, so it belongs beside seed_media.yml and not inside anyone's folder.
#
# The render cell is self-contained diffusers rather than a call into the
# ai-toolkit render path, and that is deliberate. That path composes a prompt
# from the shoots schema — trigger, descriptor, scene, key, distance, lens,
# stock — and prepends the subject to every one. Two of these three populations
# must have no subject in front of them, and all sixty-one must land on an exact
# filename the seeds already look up. Bending the shoots renderer into that shape
# would leave neither job legible.

