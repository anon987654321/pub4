LORA_ROOT = Pathname.new(__dir__).join("..").expand_path
SPEC = LORA_ROOT.join("seed_media.yml")
NOTEBOOK = LORA_ROOT.join("seed_media.ipynb")
REPO = ENV.fetch("PUB4_REPO", "anon987654321/pub4")
