# frozen_string_literal: true

require "yaml"

module Backlog
  # The store side of the generator: entries to data/backlog.yml and back.
  # The rows come from Backlog.generate; this module holds the artifact
  # contract — refuse a hand-curated row instead of clobbering it, and fail
  # loudly when the file no longer matches TODO.md.
  module Store
    # A span counts as a done-when only when the item actually asks for a
    # command run. Text proposes tools by name ("bin/vps-deploy") and cites
    # commands as history; the execution verb in the prose is what separates
    # a named acceptance command from a named path.
    EXEC_HINT = /
      \b(?:run(?:s|ning)?|ran|re-?runs?|re-?ran|executes?d?|verif(?:y|ied|ies)|
      validate[sd]?|confirm(?:s|ed)?|proves?|measure[sd]?|audits?|refresh(?:es)?|
      captures?d?)\b
    /xi.freeze

    # Psych folds scalars at line_width but never breaks a token, so no single
    # width is safe: the line law caps files at 120 and the source overruns it
    # at every width tried singly. Walk the ladder and keep the first dump
    # that fits; the smallest carries the day if even it cannot, which leaves
    # the finding visible instead of hidden.
    DUMP_WIDTHS = [100, 70, 55, 40].freeze
    LINE_CAP = 120

    module_function

    def dump_yaml(payload)
      DUMP_WIDTHS.each do |width|
        text = YAML.dump(payload, line_width: width)
        return text if text.lines.map(&:length).max <= LINE_CAP
      end

      YAML.dump(payload, line_width: DUMP_WIDTHS.last)
    end

    def write(source: Backlog::SOURCE, out: Backlog::DEST, refresh: false, io: $stdout)
      entries = Backlog.generate(source:)
      conflicts = text_conflicts(entries, out)
      return refuse(conflicts, io) unless conflicts.empty? || refresh

      File.write(out, header + dump_yaml(payload(entries)))
      io.puts "backlog: #{conflicts.empty? ? "wrote" : "refreshed"} #{entries.size} entries " \
              "from TODO.md into #{File.basename(out)}"
      0
    end

    def check(source: Backlog::SOURCE, out: Backlog::DEST, io: $stdout)
      raise "missing #{out}" unless File.file?(out)

      rows = live_rows(out)
      fresh = Backlog.generate(source:).map { |row| row.transform_keys(&:to_s) }

      if rows == fresh
        io.puts "backlog check: CLEAN — #{fresh.size} entries match TODO.md"
        return 0
      end

      io.puts "backlog check: STALE — data/backlog.yml no longer matches the source; rerun MASTER/tools/backlog.rb"
      1
    end

    def parse_cli(argv)
      argv = argv.dup
      mode_check = argv.delete("--check") == "--check"
      refresh = argv.delete("--refresh") == "--refresh"
      flags = take_flags(argv)
      raise "backlog: unknown arguments #{argv.join(" ")}" unless argv.empty?

      {
        check: mode_check,
        refresh:,
        source: flags.fetch(:source, Backlog::SOURCE),
        out: flags.fetch(:out, Backlog::DEST),
      }
    end

    def header
      <<~HEADER
        # Generated by MASTER/tools/backlog.rb from TODO.md at the repository root.
        # Do not edit by hand: TODO.md is the one source, curation happens there
        # or in the generator's classification rules, and `--check` fails the next
        # audit when this file no longer matches it.
      HEADER
    end

    def refuse(conflicts, io)
      conflicts.each do |id|
        io.puts "backlog: REFUSED #{id} carries text that differs from TODO.md; rerun with --refresh to regenerate"
      end
      1
    end

    def text_conflicts(entries, out)
      return [] unless File.file?(out)

      named = existing_rows(out).filter_map { |row| [row["id"], row["text"]] if row["text"] }
      named.select { |id, text| entries.any? { |row| row[:id] == id && row[:text] != text } }
           .map(&:first)
    end

    def existing_rows(out)
      current = YAML.load_file(out)
      return [] unless current.is_a?(Hash)

      (current["entries"] || []).select { |row| row.is_a?(Hash) }
    end

    def live_rows(out)
      existing_rows(out).map { |row| row.transform_keys(&:to_s) }
    end

    def payload(entries)
      # String keys so the file loads through plain YAML indexing; Psych
      # would serialize symbol keys as ":schema:".
      {
        "schema" => 1,
        "name" => "pub4_backlog",
        "generated_by" => "MASTER/tools/backlog.rb",
        "source" => "TODO.md (repository root)",
        "entry_count" => entries.size,
        "entries" => entries.map { |row| row.transform_keys(&:to_s) },
      }
    end

    def take_flags(argv)
      flags = {}
      while (at = argv.index { |arg| %w[--source --out].include?(arg) })
        name = argv.delete_at(at)
        value = argv.delete_at(at)
        raise "backlog: #{name} needs a value" if value.nil?

        flags[name.sub(%r{\A--}, "").to_sym] = value
      end
      flags
    end
  end
end
