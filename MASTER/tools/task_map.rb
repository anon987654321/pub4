# frozen_string_literal: true

require "yaml"

module Operator
  class TaskMap
    ROOT = File.expand_path("..", __dir__)
    SOURCE = File.join(ROOT, "data", "task_map.yml")
    OUTPUT = File.join(ROOT, "docs", "task-map.md")

    def self.render(source: SOURCE)
      data = YAML.safe_load_file(source, permitted_classes: [], aliases: false)
      raise ArgumentError, "task map schema must be version 1" unless data.is_a?(Hash) && data["schema"] == 1
      tasks = data.fetch("tasks")
      raise ArgumentError, "task map must contain task rows" unless tasks.is_a?(Array) && tasks.any?

      rows = tasks.map do |row|
        raise ArgumentError, "task map row must be a mapping" unless row.is_a?(Hash)
        %w[task start proof].each do |key|
          raise ArgumentError, "task map row is missing #{key}" if row[key].to_s.strip.empty?
        end
        "| #{cell(row.fetch("task"))} | #{cell(row.fetch("start"))} | #{cell(row.fetch("proof"))} |"
      end
      [
        "<!-- Generated by cd MASTER && rake docs:task_map from data/task_map.yml. Edit the source and regenerate. -->",
        "",
        "# MASTER task map",
        "",
        "Choose the row closest to the requested work. This is navigation, not a new source of policy; the live Laws and owning tree contract remain authoritative.",
        "",
        "| Task | Start here | Minimum proof |",
        "|---|---|---|",
        *rows,
        "",
      ].join("\n")
    rescue Psych::Exception => error
      raise ArgumentError, "task map source is unreadable: #{error.message}"
    end

    def self.write(output: OUTPUT, source: SOURCE)
      rendered = render(source:)
      File.write(output, rendered)
      rendered
    end

    def self.check(output: OUTPUT, source: SOURCE)
      expected = render(source:)
      return true if File.file?(output) && File.read(output) == expected
      raise ArgumentError, "task-map output drifted; run cd MASTER && rake docs:task_map"
    end

    def self.cell(value)
      value.to_s.gsub("|", "\\|").gsub(/\s+/, " ").strip
    end
    private_class_method :cell
  end
end

if $PROGRAM_NAME == __FILE__
  if ARGV.include?("--check")
    Operator::TaskMap.check
    puts "task_map: current"
  else
    Operator::TaskMap.write
    puts "task_map: wrote docs/task-map.md"
  end
end
