# frozen_string_literal: true

# The laws digest: one line per declared law, generated so it can be read
# instead of 2,170 lines of laws.yml and the 328 Law.define blocks the
# executable files hold. Authority never moves — data/laws.yml and law/*.rb
# stay the only sources; this file is a table of contents over them, the way
# agent_contracts generates its copies.
#
#   cd MASTER && rake docs:laws_digest      # regenerate docs/laws_digest.md
#   cd MASTER && rake lint:laws_digest      # fail when the file drifted
#
# Never edit docs/laws_digest.md by hand; edit the sources and regenerate.

require "yaml"

module Operator
  class LawsDigest
    ROOT = File.expand_path("../..", __dir__)
    CATALOGUE = File.join(ROOT, "MASTER", "data", "laws.yml")
    LAW_DIR = File.join(ROOT, "MASTER", "law")
    OUTPUT = File.join(ROOT, "MASTER", "docs", "laws_digest.md")
    DEFINE = /\ALaw\.define\(:([A-Z_0-9]+)\) do\s*\z/.freeze
    FIX = /\A\s+fix\s+"(.*)"\s*\z/.freeze
    SEVERITY = /\A\s+severity\s+:(info|warning|error|critical|veto)\s*\z/.freeze

    attr_reader :entry_count

    def self.render(catalogue_path: CATALOGUE, law_dir: LAW_DIR)
      new(catalogue_path:, law_dir:).render
    end

    def self.write(catalogue_path: CATALOGUE, law_dir: LAW_DIR, output: OUTPUT)
      digest = render(catalogue_path:, law_dir:)
      File.write(output, digest)
      digest
    end

    def initialize(catalogue_path: CATALOGUE, law_dir: LAW_DIR)
      @catalogue_path = catalogue_path
      @law_dir = law_dir
      @entry_count = 0
    end

    def render
      out = +"# Laws digest (generated)\n\n"
      out << "Generated by `rake docs:laws_digest` from `MASTER/data/laws.yml` and `MASTER/law/*.rb`.\n"
      out << "A navigation aid, never an authority: the statement here is the source's own\n"
      out << "sentence, and where this file and a source disagree the source wins and the\n"
      out << "digest is regenerated. `rake lint:laws_digest` fails when the file has drifted.\n\n"

      catalogue = YAML.safe_load_file(@catalogue_path, aliases: true)
      @catalogue_entries = catalogue.filter_map do |id, row|
        [id.to_s, row] if row.is_a?(Hash) && row["statement"].is_a?(String)
      end.to_h
      out << "## Normative laws (data/laws.yml)\n\n"
      @catalogue_entries.each do |id, row|
        labels = []
        labels << "node: #{row["node"]}" if row["node"]
        labels << "parent: #{row["parent"]}" if row["parent"]
        labels << "root: #{row["root"]}" if row["root"]
        labels << "severity: #{row["severity"]}" if row["severity"]
        out << "- **#{id}**"
        out << " (#{labels.join("; ")})" unless labels.empty?
        out << " — #{row["statement"].to_s.strip.gsub(/\s+/, " ")}\n"
        @entry_count += 1
      end

      out << "\n## Executable laws (law/*.rb)\n\n"
      out << "One line per `Law.define`: id, severity, and the law's own fix sentence.\n\n"
      Dir.glob(File.join(@law_dir, "*.rb")).sort.each do |path|
        laws = extract(File.readlines(path, chomp: true))
        next if laws.empty?

        out << "### law/#{File.basename(path)} (#{laws.size} laws)\n\n"
        laws.each do |law|
          line = +"- #{law[:id]}"
          line << " (#{law[:severity]})" if law[:severity]
          line << " — #{law[:fix]}" if law[:fix]
          out << line << "\n"
          @entry_count += 1
        end
        out << "\n"
      end

      out << "---\n\n#{@entry_count} entries. Regenerate with `cd MASTER && rake docs:laws_digest`.\n"
      out
    end

    private

    # Resolve severity from the canonical declaration or its declared parent.
    def severity_of(id, seen = {})
      key = id.to_s
      return if seen[key]

      seen[key] = true
      row = @catalogue_entries && @catalogue_entries[key]
      return unless row

      row["severity"] || severity_of(row["parent"], seen)
    end

    # Block-scoped, not regex-global: a law is the lines between its
    # Law.define header and the column-0 end that closes it, so a comment
    # mentioning another law's id or a fixture string can never be counted.
    def extract(lines)
      laws = []
      current = nil
      lines.each do |line|
        if current.nil?
          header = line.match(DEFINE)
          current = { id: header[1], severity: severity_of(header[1]), fix: nil } if header
        elsif line == "end"
          laws << current
          current = nil
        else
          current[:fix] ||= line.match(FIX)&.[](1)
          current[:severity] ||= line.match(SEVERITY)&.[](1)
        end
      end
      laws
    end
  end
end
