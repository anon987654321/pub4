# frozen_string_literal: true

# The map a reader needs before they can grep: which file declares which
# constant, and which local files it pulls in. "Where does X happen?" cost a
# 34 KB read and a six-hop trace during the 2026-10-28 boot crash; this file
# is the answer as data. Generated, not maintained: `rake docs:map` writes
# MASTER/docs/map.md and `rake lint:map` fails when the tree and the file
# disagree. agent_context --tree serves the per-prompt handoff; this serves
# the reader who cannot run the tool first.

require "set"

MASTER_ROOT = File.expand_path("..", __dir__)
LIB = File.join(MASTER_ROOT, "lib")
TARGET = File.join(MASTER_ROOT, "docs", "map.md")

def declared_constants(source)
  nesting = []
  constants = []
  source.each_line do |line|
    match = line.match(/\A(\s*)(module|class)\s+([A-Z]\w*)\b/)
    next unless match

    level = match[1].size / 2
    nesting = nesting[0...level]
    nesting[level] = match[3]
    constants << nesting.compact.join("::")
  end
  constants
end

def local_requires(source, path)
  dir = File.dirname(path)
  source.scan(/require_relative\s+"([^"]+)"/).flatten.filter_map do |target|
    resolved = File.expand_path(target, dir)
    next unless resolved.start_with?(LIB) && File.file?("#{resolved}.rb")

    resolved.delete_prefix("#{LIB}/").delete_suffix(".rb")
  end
end

rows = Dir.glob(File.join(LIB, "**", "*.rb")).sort.filter_map do |path|
  source = File.read(path)
  relative = path.delete_prefix("#{LIB}/")
  constants = declared_constants(source)
  requires = local_requires(source, path)
  next if constants.empty? && requires.empty?

  [relative, constants, requires]
end

out = String.new(<<~HEADER)
  <!-- Generated by `cd MASTER && rake docs:map` from tools/tree_map.rb.
       Edit the generator, not this file: rake lint:map fails when they
       disagree. -->

  # MASTER/lib map

  #{rows.size} files under `lib/`, sorted. Per file: the constants it declares
  (nesting approximated from two-space indentation) and the files under
  `lib/` it require_relatives. The boot chain this map serves:
  `bin/master` → `lib/boot/master_boot.rb` → `bootstrap_container` →
  `lib/builder.rb` → `lib/builder/ai_boot.rb` → `lib/fix/kernel.rb` →
  `lib/fix/kernel/lifecycle.rb` → `lib/fix/kernel/convergence_adapter.rb`;
  `tools/kernel_autoload_smoke.rb` walks it on every audit.

HEADER

rows.each do |relative, constants, requires|
  out << "## `lib/#{relative}`\n\n"
  if constants.any?
    out << "Declares: #{constants.map { |c| "`#{c}`" }.join(', ')}\n"
  end
  if requires.any?
    out << "Requires: #{requires.map { |r| "`#{r}`" }.join(', ')}\n"
  end
  out << "\n"
end

if ARGV.include?("--check")
  committed = File.file?(TARGET) ? File.read(TARGET) : ""
  if committed != out
    warn "tree_map: docs/map.md is stale against lib/ — run `cd MASTER && rake docs:map`"
    exit 1
  end
  puts "tree_map: docs/map.md matches lib/ (#{rows.size} files)"
else
  File.write(TARGET, out)
  puts "tree_map: wrote docs/map.md (#{rows.size} files)"
end
