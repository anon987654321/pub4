#!/usr/bin/env ruby
# frozen_string_literal: true

# Rewrites non-ASCII punctuation to ASCII in tracked files (Law ASCII_PUNCTUATION).
#
#   ruby MASTER/tools/ascii_punctuation.rb [--write] PATH...
#
# Without --write it reports what would change. A file whose rewrite does not
# parse, or whose YAML or JSON would load to different data than its own with
# only the punctuation changed, is left as it is and listed for a person.

require "json"
require "open3"
require "tmpdir"
require "prism"
require "yaml"
require_relative "../lib/content/ascii_punctuation"

module AsciiPunctuationSweep
  Text = Master::Content::AsciiPunctuation
  RubyText = Master::Content::AsciiPunctuationRuby

  # Third-party, compiled or generated bytes, and the operator's soul.yml.
  SKIP = %r{
    (?:\A|/)(?:vendor|node_modules|tmp|log|coverage)/ | /public/assets/ | /app/assets/builds/ |
    \.min\.(?:js|css)\z | (?:\A|/)(?:Gemfile|yarn)\.lock\z | package-lock\.json\z |
    (?:\A|/)MASTER/data/soul\.yml\z | (?:\A|/)snapshot_[A-Z]+\.md\z | face\.runtime\.js\z
  }x

  RUBY_NAMES = %w[Rakefile Gemfile Capfile Guardfile].freeze
  EXTENSION_KINDS = {
    ".rb" => :ruby, ".rake" => :ruby, ".gemspec" => :ruby, ".ru" => :ruby, ".erb" => :erb,
    ".yml" => :yaml, ".yaml" => :yaml, ".json" => :json, ".js" => :js, ".mjs" => :js,
    ".py" => :python, ".sh" => :script, ".zsh" => :script,
  }.freeze
  SHEBANG_KINDS = [[/ruby/, :ruby], [/python/, :python], [/\b(?:k?sh|zsh|bash)\b/, :script]].freeze
  # The face runtime's sources are JavaScript split in parts no parser takes alone.
  JS_PART = /\Aface\.part\d+\.txt\z/
  YAML_CLASSES = [Symbol, Date, Time].freeze

  module_function

  def run(argv)
    write = argv.delete("--write")
    tally = Hash.new(0)
    manual = []

    files(argv).each do |path|
      outcome = sweep(path, write:)
      tally[outcome] += 1
      manual << path if outcome == :manual
    end
    puts "ascii0: #{tally.sort.map { |k, v| "#{k} #{v}" }.join(", ")}#{write ? "" : " (dry run)"}"
    manual.each { |path| puts "ascii0: manual #{path}" }
  end

  def files(roots)
    out, status = Open3.capture2("git", "ls-files", "-z", "--", *roots)
    abort "ascii0: git ls-files failed" unless status.success?

    out.split("\0").reject { |path| path.match?(SKIP) || !File.file?(path) || File.symlink?(path) }
  end

  def sweep(path, write:)
    source = File.binread(path).force_encoding(Encoding::UTF_8)
    return :binary unless source.valid_encoding? && !source.include?("\0")
    return :clean unless Text.banned?(source)

    result = rewritten(path, source)
    return :manual unless result && !Text.banned?(result)

    File.binwrite(path, result) if write
    :rewritten
  end

  HANDLERS = {
    ruby: ->(source) { RubyText.rewrite(source) },
    erb: ->(source) { erb(source) },
    yaml: ->(source) { same_data(source, rewrite: ->(text) { yaml(text) }) { |text| yaml_load(text) } },
    json: ->(source) { same_data(source) { |text| JSON.parse(text) } },

    script: ->(source) { judged(source, Text.rewrite(source)) { |text| syntax_ok?(shell_of(source), text) } },
    js: ->(source) { javascript(source) },
    js_part: ->(source) { javascript(source, check: false) },
    python: ->(source) { judged(source, Text.rewrite(source)) { |text| python_ok?(text) } },
    text: ->(source) { Text.rewrite(source) },
  }.freeze

  def rewritten(path, source) = HANDLERS.fetch(kind(path, source)).call(source)

  def yaml_load(text) = YAML.safe_load(text, aliases: true, permitted_classes: YAML_CLASSES)

  def kind(path, source)
    name = File.basename(path)
    return :ruby if RUBY_NAMES.include?(name)
    return :js_part if name.match?(JS_PART)

    EXTENSION_KINDS.fetch(File.extname(name)) { shebang_kind(source) }
  end

  def shebang_kind(source)
    line = source.start_with?("#!") ? source.lines.first : ""
    SHEBANG_KINDS.find { |pattern, _| line.match?(pattern) }&.last || :text
  end

  # A template is HTML with Ruby tags in it. The HTML is copy; a curly quote
  # inside an attribute value becomes an entity so it cannot close the value.
  # A tag keeps its rewrite only when Ruby lexes it to the same tokens.
  ERB_TAG = /(<%.*?%>)/m
  ATTRIBUTE = /(?<name>\s[\w:.@-]+=)(?<quote>["'])(?<value>[^"'<>]*?)\k<quote>/

  # Copy that meets a Ruby tag runs on into the tag's output, so a dash at
  # that edge keeps its space; a comment tag leaves nothing to run into.
  def erb(source)
    parts = source.split(ERB_TAG)
    parts.each_with_index.map do |part, index|
      next erb_tag(part) if part.start_with?("<%")

      html(part, before: index.positive? && code_tag?(parts[index - 1]) ? "x" : nil,
                 after: code_tag?(parts[index + 1]) ? "x" : nil)
    end.join
  rescue ArgumentError => e
    warn "ascii0: template left for a person, #{e.message}"
    nil
  end

  def erb_tag(tag)
    return tag unless Text.banned?(tag)

    ruby = ruby_tag(tag)
    return ruby if ruby

    out = Text.rewrite(tag)
    return out if tag.start_with?("<%#")
    raise ArgumentError, "tag changes meaning" unless tokens(tag) == tokens(out)

    out
  end

  # A tag whose Ruby parses on its own goes through the Ruby rewriter.
  def ruby_tag(tag)
    open, code, close = tag.match(/\A(<%[=-]?)(.*?)(-?%>)\z/m)&.captures
    return unless code && !tag.start_with?("<%#") && Prism.parse(code).success?

    out = RubyText.rewrite(code)
    out && "#{open}#{out}#{close}"
  end

  def tokens(tag)
    code = tag[/\A<%[=#-]?(.*?)-?%>\z/m, 1].to_s
    Prism.lex(code).value.map { |token, _| token.type }
  end

  DOUBLE_ENTITIES = { "\u201C" => "&quot;", "\u201D" => "&quot;" }.freeze
  SINGLE_ENTITIES = { "\u2018" => "&#39;", "\u2019" => "&#39;" }.freeze

  def code_tag?(part) = part.to_s.start_with?("<%") && !part.start_with?("<%#")

  def html(text, before: nil, after: nil)
    return text unless Text.banned?(text)

    text.gsub(ATTRIBUTE) do
      name, quote, value = Regexp.last_match.captures
      entity = quote == '"' ? DOUBLE_ENTITIES : SINGLE_ENTITIES
      "#{name}#{quote}#{value.gsub(Regexp.union(entity.keys), entity)}#{quote}"
    end.then { |escaped| Text.rewrite(escaped, before:, after:) }
  end

  # The rewrite must load to the original's data with every string rewritten.
  def same_data(source, rewrite: ->(text) { Text.rewrite(text) }, &load)
    out = rewrite.call(source)
    expected = deep_rewrite(load.call(source))
    load.call(out) == expected ? out : nil
  rescue StandardError => e
    warn "ascii0: data check failed, #{e.class}: #{e.message}"
    nil
  end

  def deep_rewrite(value)
    return Text.rewrite(value) if value.is_a?(String)
    return value.map { |item| deep_rewrite(item) } if value.is_a?(Array)
    return value unless value.is_a?(Hash)

    value.to_h { |key, item| [deep_rewrite(key), deep_rewrite(item)] }
  end

  # JavaScript is read token by token on each line: a regex literal, or a
  # string the code compares or hands to a matching call, keeps its marks
  # as \u escapes; a comment or any other string is copy and becomes ASCII.
  JS_TOKEN = %r{
    # a quoted or template string
    (?<string>'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`(?:\\.|[^`\\])*`) |
    # a line or block comment
    (?<comment>//.*|/\*.*?(?:\*/|\z)) |
    # a regex literal, where an expression may start
    (?<regex>(?:(?<=[(,=:\[!&|?{};])|^|(?<=\s))/(?![/*\s])(?:\\.|\[(?:\\.|[^\]\\\n])*\]|[^/\\\n\[])+/[a-z]*)
  }x
  JS_DATA_CALL = /
    (?:replace(?:All)?|split|includes|indexOf|lastIndexOf|startsWith|endsWith|test|match(?:All)?|search)\s*\(\s*\z
  /x
  JS_COMPARED_BEFORE = /[!=]==?\s*\z/
  JS_DATA_AFTER = /\A\s*(?:[!=]==?|\.(?:includes|indexOf|split|test|startsWith|endsWith)\s*\()/

  def javascript(source, check: true)
    out = source.lines.map { |line| javascript_line(line) }.join
    !check || node_ok?(out) ? out : nil
  end

  def javascript_line(line)
    return line unless Text.banned?(line)
    return Text.rewrite(line) if line.lstrip.start_with?("//", "*", "/*")

    out = +""
    pos = 0
    line.to_enum(:scan, JS_TOKEN).each do
      match = Regexp.last_match
      out << Text.rewrite(line[pos...match.begin(0)]) << javascript_token(match)
      pos = match.end(0)
    end
    out << Text.rewrite(line[pos..])
  end

  def javascript_token(match)
    token = match[0]
    return token unless Text.banned?(token)
    return escape_marks(token) if match[:regex]
    return Text.rewrite(token) if match[:comment]
    return escape_marks(token) if match.pre_match.match?(JS_DATA_CALL) || match.pre_match.match?(JS_COMPARED_BEFORE) ||
                                  match.post_match.match?(JS_DATA_AFTER)

    quote = token[0]
    curly = Regexp.union(Text::REPLACEMENTS.select { |_, ascii| ascii == quote }.keys)
    "#{quote}#{Text.rewrite(token[1...-1].gsub(curly) { "\\#{quote}" })}#{quote}"
  end

  def escape_marks(text) = text.gsub(Text::BANNED) { |mark| format("\\u%04X", mark.ord) }

  def node_ok?(out)
    Dir.mktmpdir do |dir|
      file = File.join(dir, "check.mjs")
      File.write(file, out)
      _, status = Open3.capture2e("node", "--check", file)
      status.success?
    end
  end

  # Python parses its own rewrite, when it parses the original; LaTeX and
  # other prose fall through to the text rewrite.
  PYTHON_PARSE = "import ast, sys; ast.parse(sys.stdin.read())"

  def python_ok?(text)
    _, status = Open3.capture2e("python3", "-c", PYTHON_PARSE, stdin_data: text)
    status.success?
  rescue Errno::ENOENT
    false
  end

  # A file's own parser (its shell, python3) judges the rewrite, and only when
  # it accepts the original.
  def judged(source, out)
    return out unless yield(source)

    yield(out) ? out : nil
  end

  def shell_of(source) = source.lines.first.to_s[%r{\A#!\s*(?:/usr)?/bin/(?:env\s+)?(ksh|zsh|bash|sh)\b}, 1] || "sh"

  def syntax_ok?(shell, text)
    _, status = Open3.capture2e(shell, "-n", stdin_data: text)
    status.success?
  end

  # A quoted YAML scalar escapes its own quote; a value left as a bare "-" is quoted.
  YAML_QUOTED = /
    \A(?<prefix>\s*(?:-\s+)?[^\#\s"'][^:]*:\s+|\s*-\s+)
    (?<quote>["'])(?<inner>.*)\k<quote>(?<rest>[ \t]*(?:\#.*)?)\n?\z
  /x
  YAML_DASH_VALUE = /\A(\s*[^#\s][^:]*:\s+)(-(?:\s.*)?)\s*\z/

  def yaml(text) = text.lines.map { |line| yaml_line(line) }.join

  def yaml_line(line)
    return line unless Text.banned?(line)

    if (match = line.match(YAML_QUOTED))
      prefix, quote, inner, rest = match.captures
      return "#{prefix}#{quote}#{quoted(inner, quote)}#{quote}#{rest}#{line.end_with?("\n") ? "\n" : ""}"
    end
    out = Text.rewrite(line)
    (dash = out.chomp.match(YAML_DASH_VALUE)) ? "#{dash[1]}\"#{dash[2]}\"#{out.end_with?("\n") ? "\n" : ""}" : out
  end

  def quoted(inner, quote)
    curly = Regexp.union(Text::REPLACEMENTS.select { |_, ascii| ascii == quote }.keys)
    escaped = quote == '"' ? '\\"' : "''"
    Text.rewrite(inner.gsub(curly) { escaped })
  end
end

AsciiPunctuationSweep.run(ARGV) if $PROGRAM_NAME == __FILE__
