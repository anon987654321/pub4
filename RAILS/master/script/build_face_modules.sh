#!/bin/sh
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
. "$ROOT/script/bundle_size.sh"
OUT="$ROOT/public/face.modules.bundle.js"
ENTRY="$ROOT/script/face_modules_entry.js"
SOURCE_DIGEST="$(ruby -rdigest -e 'paths = ARGV.sort; puts Digest::SHA256.hexdigest(paths.map { |p| File.binread(p) }.join("\0"))' \
  "$ENTRY" "$ROOT/public/face_blendshape_bridge.js" "$ROOT/public/face_particles.js" "$ROOT/public/face_audio_bridge.js" "$ROOT/public/face_tts_bridge.js" "$ROOT/public/face_expression_bridge.js" "$ROOT/public/face_council_multi.js" "$ROOT/public/face_phosphor_trail.js" "$ROOT/public/face_micro_interactions.js" "$ROOT/public/face_perf_guards.js" "$ROOT/public/face_brutalist.js")"
if npx --yes esbuild@0.25.9 "$ENTRY" \
  --bundle \
  --format=esm \
  --platform=browser \
  --target=es2020 \
  --outfile="$OUT"; then
  ruby -e 'p, digest = ARGV; body = File.read(p); marker = "// SOURCE-SET-SHA256: #{digest}\n"; body = body.sub(/\A/, marker); File.write(p, body)' "$OUT" "$SOURCE_DIGEST"
else
  # The modules are ordered side-effect-only IIFEs. Keep the bundle buildable
  # on an offline OpenBSD host without downloading a new toolchain.
  ruby -e '
    out, entry, digest = ARGV
    imports = File.readlines(entry).filter_map { |line| line.match(/^\s*import "\.\.\/public\/([^"]+)";/) }.map { |match| File.join(File.dirname(entry), "..", "public", match[1]) }
    segments = ["// Generated by script/build_face_modules.sh — source-assembled fallback; esbuild runner unavailable.", "// SOURCE-SET-SHA256: #{digest}"]
    imports.each do |path|
      raise "missing module source #{path}" unless File.file?(path)
      segments << "// public/#{File.basename(path)}" << File.read(path, encoding: "UTF-8") << ""
    end
    File.binwrite(out, segments.join("\n"))
  ' "$OUT" "$ENTRY" "$SOURCE_DIGEST"
fi
report_bundle_size "$OUT"
